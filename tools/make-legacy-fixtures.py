"""Create original, small wire-format fixtures; no published replay data is used."""

from pathlib import Path
import struct

root = Path(__file__).resolve().parents[1] / "inst" / "extdata" / "legacy"
root.mkdir(parents=True, exist_ok=True)


def text(name, header, records):
    (root / name).write_text(
        header + "\n" + "\n".join(records) + "\n", encoding="ascii"
    )


def u32(b, o, v):
    b[o : o + 4] = struct.pack("<I", v)


# Two pads: each performs one button check while the other checks its opposite.
b = bytearray(144)
b[:4] = b"FMV\x1a"
b[5] = 0xE0
u32(b, 10, 4)
b[16:32] = b"Original fixture"
(root / "buttons.fmv").write_bytes(
    b + b"".join(bytes([1 << i, 1 << (7 - i), i % 3]) for i in range(8))
)
for name, gg, old in [
    ("sms.mmv", False, False),
    ("gg.mmv", True, False),
    ("sms-old.mmv", False, True),
]:
    b = bytearray(96 if old else 244)
    b[:4] = b"MMV\0"
    u32(b, 4, 0x1160)
    u32(b, 8, 8)
    u32(b, 16, 1)
    if not old:
        u32(b, 24, len(b))
        u32(b, 28, 2)
        u32(b, 96, 8 if gg else 0)
    (root / name).write_bytes(
        b + b"".join(bytes([1 << i, 1 << (7 - i)]) for i in range(8))
    )
for name, mnemonics, header in [
    ("pce.mc2", "UDLR12NS", "version 1\nports 2"),
    ("vboy.mc2", "SWCT^v<>ENLRBA", "version 1\nemulator VBjin\nports 1"),
    ("saturn.ymv", "LRUDSABCXYZWE", "version 1\nisPal 0"),
]:
    records = []
    for i, m in enumerate(mnemonics):
        pad = "." * i + m + "." * (len(mnemonics) - i - 1)
        other = "|" + "." * len(mnemonics) if name == "pce.mc2" else ""
        records.append("|" + str(i % 3) + "|" + pad + other + "|")
    text(name, header, records)
(root / "pce-binary.mc2").write_bytes(
    b"version 1\nports 2\nbinary 1\n|" + struct.pack("<BHHBHH", 1, 128, 1, 2, 8, 4)
)
(root / "saturn-binary.ymv").write_bytes(
    b"version 1\nbinary 1\n|" + struct.pack("<BHBH", 1, 4096, 2, 1)
)
# Stylus trace, microphone, lid, and separate Select/Start presses.
for v in [1, 2]:
    records = []
    for i in range(6):
        pad = (
            "....T........"
            if i == 0
            else ".....S......." if i == 1 else "............."
        )
        records.append(
            f"|{[0,0,1,4,2,0][i]}|{pad}{20+30*i:03} {10+20*i:03} {int(i<4)}"
            + (f" {i:03}" if v == 2 else "")
            + "|"
        )
    text(f"touch-v{v}.dsm", f"version {v}\nemuVersion 91200", records)
(root / "touch-binary.dsm").write_bytes(
    b"version 1\nbinary 1\n|"
    + struct.pack("<BHBBBBHBBB", 1, 256, 40, 50, 1, 4, 128, 60, 70, 0)
)
for system, ports, width in [
    ("pce", 5, 2),
    ("lynx", 1, 2),
    ("wswan", 1, 2),
    ("ngp", 1, 1),
    ("pcfx", 2, 2),
    ("sms", 2, 1),
    ("nes", 4, 1),
]:
    b = bytearray(256)
    b[:8] = b"MDFNMOVI"
    u32(b, 8, 0x80A)
    u32(b, 12, 1)
    b[116 : 116 + len(system)] = system.encode()
    data = bytearray()
    for i in range(width * 8):
        data.append(i % 3)
        for port in range(ports):
            data.extend((1 << i if port == 0 else 0).to_bytes(width, "little"))
    (root / (system + ".mcm")).write_bytes(b + data)
(root / "README.txt").write_text(
    "These recordings are original fixtures generated by tools/make-legacy-fixtures.py.\nThey contain button checks, two-controller contrasts, a stylus trace, and command events.\nNo game recordings, ROMs, BIOS files, or third-party savestates are included.\n",
    encoding="ascii",
)

# CTM: button checks followed by touch, motion sensors, and both C-stick encodings.
b = bytearray(256)
b[:4] = b"CTM\x1b"
u32(b, 80, 3)
b[84:92] = struct.pack("<Q", 14)
records = []
for i in range(14):
    x, y = [(154, 0), (0, 154), (-154, 0), (0, -154)][i % 4]
    records.append(struct.pack("<BHhh", 0, 1 << i, x, y))
records.extend(
    [
        struct.pack("<BHHBB", 1, 250, 190, 1, 0),
        struct.pack("<Bhhh", 2, -123, 456, -789),
        struct.pack("<Bhhh", 3, 1234, -2345, 3456),
        struct.pack("<BhhBB", 4, 156, 0, 1, 0),
        struct.pack("<BhhBB", 4, 0, -156, 0, 1),
        struct.pack("<BIH", 5, 31 + 64 + 128 + (2048 << 8) + (4095 << 20), 0),
        struct.pack("<BIH", 5, 31 + 32 + 128 + (1 << 8) + (2048 << 20), 0),
    ]
)
(root / "devices.ctm").write_bytes(b + b"".join(records))

# Enhanced ZMV: two pads, a repeated hold, a chapter, and a reset before release.
b = bytearray(40)
b[:3] = b"ZMV"
b[3:5] = struct.pack("<H", 151)
u32(b, 9, 5)
b[30:32] = struct.pack("<H", 1)
b[37:39] = struct.pack("<H", 0xC000)
b[39] = 0xC0
stream = bytearray([0xC0, 0x80, 0x00, 0x08, 2]) + struct.pack("<I", 4)
chapter_offset = 43 + len(stream) + 1
stream += bytes([4]) + bytes(18) + bytes([1, 0x80, 0x01, 0x00])
(root / "holds.zmv").write_bytes(
    b + bytes(3) + stream + struct.pack("<I", chapter_offset) + bytes(2)
)
# GZM: every named N64 button, original axes, reset, seed, and sync events.
bits = list(range(15, 7, -1)) + list(range(5, -1, -1))
rows = [
    struct.pack(
        ">HbbH", 1 << bit, [-128, -64, 0, 64, 127][i % 5], 0, 128 if i == 0 else 0
    )
    for i, bit in enumerate(bits)
]
payload = (
    struct.pack(">IIHbb", len(rows), 1, 0, 0, 0)
    + b"".join(rows)
    + struct.pack(">III", 2, 0x12345678, 0xFEDCBA98)
)
payload += (
    struct.pack(">III", 1, 1, 1)
    + struct.pack(">IHbb", 3, 0x8000, -60, 60)
    + struct.pack(">II", 4, 2)
    + struct.pack(">I", 5)
    + struct.pack(">II", 7, 13)
)
(root / "buttons.gzm").write_bytes(payload)
