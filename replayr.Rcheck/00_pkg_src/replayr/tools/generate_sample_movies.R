# Generate the redistributable sample movies in inst/extdata.
#
# The files produced here are deterministic synthetic controller streams. They
# contain no ROM, savestate, memory-card, cheat, audiovisual, or third-party
# publication data. Each movie represents approximately one minute of input:
# 3,600 frames for 60 Hz console formats and 2,100 tics for Doom at 35 Hz.

out_dir <- file.path("inst", "extdata")
if (!dir.exists(out_dir)) stop("run this script from the package root")

n60 <- 3600L
n35 <- 2100L

u32 <- function(x) {
  writeBin(as.integer(x), raw(), size = 4L, endian = "little")
}

put_u32 <- function(x, offset, value) {
  x[(offset + 1L):(offset + 4L)] <- u32(value)
  x
}

put_u64 <- function(x, offset, value) {
  x[(offset + 1L):(offset + 8L)] <- c(u32(value), raw(4L))
  x
}

put_text <- function(x, offset, text, width) {
  bytes <- charToRaw(enc2utf8(text))
  bytes <- bytes[seq_len(min(length(bytes), width))]
  if (length(bytes)) x[offset + seq_along(bytes)] <- bytes
  x
}

write_raw <- function(path, bytes) {
  con <- file(path, open = "wb")
  on.exit(close(con))
  writeBin(bytes, con)
}

write_text <- function(path, text) {
  write_raw(path, charToRaw(enc2utf8(text)))
}

write_zip <- function(path, members) {
  td <- tempfile("replayr-synthetic-zip-")
  dir.create(td)
  on.exit(unlink(td, recursive = TRUE), add = TRUE)
  for (name in names(members)) {
    fp <- file.path(td, name)
    dir.create(dirname(fp), recursive = TRUE, showWarnings = FALSE)
    write_text(fp, members[[name]])
    Sys.setFileTime(fp, as.POSIXct("2020-01-01 00:00:00", tz = "UTC"))
  }
  out <- normalizePath(path, mustWork = FALSE)
  if (file.exists(out)) unlink(out)
  old <- setwd(td)
  on.exit(setwd(old), add = TRUE)
  # -X omits filesystem-specific extra fields (including creation/access
  # times), leaving a byte-for-byte reproducible archive.
  status <- suppressWarnings(utils::zip(out, names(members), flags = "-q -X"))
  if (!identical(status, 0L) && !file.exists(out)) {
    stop("could not create ", path)
  }
}

# Canonical NES-shaped state: Right, Left, Down, Up, Start, Select, B, A.
nes_state <- function(frame, phase_offset = 0L) {
  z <- rep(FALSE, 8L)
  phase <- ((frame - 1L) %/% 30L + phase_offset) %% 4L
  z[phase + 1L] <- TRUE
  z[5L] <- frame %% 600L == 1L
  z[6L] <- frame %% 900L == 1L
  z[7L] <- frame %% 24L < 6L
  z[8L] <- frame %% 40L < 5L
  z
}

mask <- function(pressed, labels) {
  paste(ifelse(pressed, labels, "."), collapse = "")
}

active_low_byte <- function(pressed) {
  value <- 255L
  for (bit in which(pressed) - 1L) value <- value - bitwShiftL(1L, bit)
  value
}

