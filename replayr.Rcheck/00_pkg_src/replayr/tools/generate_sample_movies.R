# PXM -------------------------------------------------------------------------
psx_word <- function(frame, phase_offset = 0L) {
  s <- nes_state(frame, phase_offset)
  pressed <- rep(FALSE, 16L)
  pressed[c(1L, 4L, 5L, 6L, 7L, 8L, 15L, 16L)] <-
    c(s[6L], s[5L], s[4L], s[1L], s[3L], s[2L], s[7L], s[8L])
  value <- 0L
  for (bit in which(pressed) - 1L) value <- bitwOr(value, bitwShiftL(1L, bit))
  value
}

pxm_header <- raw(0x34L)
pxm_header[1:4] <- charToRaw("PXM ")
