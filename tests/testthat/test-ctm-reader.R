ctm_fixture <- function() system.file('extdata', 'legacy', 'devices.ctm', package = 'replayr', mustWork = TRUE)
ctm_read <- function(mode = 'raw') .configure_movie(.decode_ctm(ctm_fixture()), analog = mode)
test_that('CTM retains heterogeneous device polls and original bytes', {
  m <- ctm_read()
  expect_s3_class(m, 'replayr_poll_stream')
  expect_equal(n_observations(m), 21L)
  expect_true(is.na(n_players(m)))
  expect_error(player(m), 'unassigned')
  expect_equal(m$header$padPollCount, 14L)
  expect_equal(m$poll_fields$event_type[15:21], c('touch', 'accelerometer', 'gyroscope', 'ir_rst', 'ir_rst', 'extra_hid', 'extra_hid'))
  expect_equal(dim(m$observed_inputs), c(21L, 15L))
  expect_true(all(m$observed_inputs[1:14, 1:12]))
  # Debug and GPIO14 are bits of the pad word, not buttons of the handheld.
  expect_identical(names(system_channels(m)), c("debug", "gpio14"))
  expect_false(any(c("debug", "gpio14") %in% m$button_keys))
  expect_false(any(m$observed_inputs[16:17, ]))
  expect_equal(as.integer(m$poll_bytes[, 1]), c(rep(0L, 14), 1:4, 4L, 5L, 5L))
  a <- analog_channels(m)
  expect_equal(a[15, c('touch_x', 'touch_y', 'touch_valid')], c(touch_x = 250, touch_y = 190, touch_valid = 1))
  expect_equal(unname(a[16, c('accel_x', 'accel_y', 'accel_z')]), c(-123, 456, -789))
  expect_equal(unname(a[17, c('gyro_x', 'gyro_y', 'gyro_z')]), c(1234, -2345, 3456))
  expect_true(all(is.na(a[16, c('left_x', 'touch_x', 'right_x')])))
  expect_equal(a[20:21, 'battery_level'], c(31, 31))
  expect_equal(a[20:21, 'extra_c_stick_x'], c(2048, 1))
  expect_equal(a[20:21, 'extra_c_stick_y'], c(4095, 2048))
  keys <- m$button_keys
  expect_true(m$inputs[15, 1, match('l3', keys)])
  expect_identical(m$button_names[match('l3', keys)], 'Touch')
  expect_true(m$inputs[18, 1, match('l2', keys)])
  expect_true(m$inputs[19, 1, match('r2', keys)])
  expect_true(m$inputs[20, 1, match('l2', keys)])
  expect_true(m$inputs[21, 1, match('r2', keys)])
})
test_that('CTM stick modes preserve source readings and sparse device observations', {
  original <- ctm_read()
  for (mode in c('cardinal4', 'cardinal8', 'angle', 'angle+magnitude')) {
    m <- ctm_read(mode)
    v <- stick_channels(m)
    expect_identical(analog_channels(m), analog_channels(original))
    expect_equal(unname(v[1:4, 1]), c(0, 90, 180, 270))
    right <- if (mode %in% c('cardinal4', 'cardinal8')) 'right_direction' else 'right_angle'
    expect_equal(v[18:21, right], c(0, 270, 90, 180))
    expect_true(all(is.na(v[16:17, ])))
    if (mode == 'angle+magnitude') {
      expect_equal(v[1:14, 'left_magnitude'], rep(1, 14))
      expect_equal(v[18:21, 'right_magnitude'], rep(1, 4))
    }
  }
  m <- ctm_read(c(left = 'cardinal8', right = 'angle+magnitude'))
  expect_equal(colnames(stick_channels(m)), c('left_direction', 'right_angle', 'right_magnitude'))
})
test_that('CTM rejects unknown event types and partial polls', {
  path <- tempfile()
  on.exit(unlink(path))
  data <- readBin(ctm_fixture(), 'raw', n = file.info(ctm_fixture())$size)
  writeBin(data[-length(data)], path)
  expect_error(.decode_ctm(path), 'partial device-poll')
  data[257] <- as.raw(99)
  writeBin(data, path)
  expect_error(.decode_ctm(path), 'unknown CTM')
})
