test_that("observation_unit() names what a row stands for", {
  unit <- function(...) observation_unit(read_movie(system.file("extdata", ..., package = "replayr")))
  expect_identical(unit("sample.fm2"), "frame")
  expect_identical(unit("sample.bk2"), "frame")
  expect_identical(unit("sample.smv"), "frame")
  expect_identical(unit("sample.m64"), "controller poll")
  expect_identical(unit("sample.dtm"), "controller poll")
  expect_identical(unit("paper", "unassigned.dtm"), "controller poll")
  expect_identical(unit("paper", "wii-motion.dtm"), "Wii Remote poll")
  expect_identical(unit("sample.lsmv"), "input subframe")
  expect_identical(unit("sample.lmp"), "game tic")
  expect_identical(unit("legacy", "devices.ctm"), "device poll")
  expect_identical(unit("legacy", "buttons.gzm"), "game update")
  expect_identical(unit("computers", "keyboard-mouse.jrsr"), "event")
  expect_identical(unit("computers", "keyboard-joystick.omr"), "event")
  expect_identical(unit("computers", "menu-double-tap.dft"), "scripted frame")
  expect_identical(unit("computers", "keyboard-jump.wtf"), "frame")
  expect_error(observation_unit(list()))
})
test_that("GameCube polls grouped by controller are polling cycles", {
  # Two enabled GameCube ports and four eight-byte polls.
  header <- raw(256)
  header[1:4] <- charToRaw("DTM\x1a")
  header[5:10] <- charToRaw("TEST01")
  header[12] <- as.raw(3)
  path <- tempfile(fileext = ".dtm")
  on.exit(unlink(path))
  writeBin(c(header, raw(32)), path)
  stream <- read_dtm(path)
  expect_s3_class(stream, "replayr_poll_stream")
  expect_identical(observation_unit(stream), "controller poll")
  grouped <- read_dtm(path, controller_order = 1:2)
  expect_identical(n_observations(grouped), 2L)
  expect_identical(observation_unit(grouped), "controller polling cycle")
})
