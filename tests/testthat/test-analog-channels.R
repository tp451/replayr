test_that("raw analogue values are the default and survive projection", {
  path <- fixture_path("sample.m64")
  raw <- read_movie(path)
  projected <- read_movie(path, analog = "cardinal8")
  expect_equal(raw$analog_mode, "raw")
  expect_equal(analog_channels(raw)[1, ], c(left_x = 70, left_y = 0))
  expect_identical(analog_channels(raw), analog_channels(projected))
  expect_false(any(button_layout(raw)$kind == "left_direction"))
  expect_true(player(projected)[1, button_layout(projected)$key == "left_e"])
  expect_equal(unname(raw$inputs), unname(projected$inputs[, , match(raw$button_ids, projected$button_ids), drop = FALSE]))
  expect_error(read_movie(path, analog = "guess"), "analog must")
  expect_error(analog_channels(raw, 1.5), "one player")
})
