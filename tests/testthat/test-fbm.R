fbm_example <- function(name) system.file("extdata", "expanded", name, package = "replayr")
test_that("an original arcade sequence retains movement, actions, and both players", {
  path <- fbm_example("synthetic-arcade.fbm")
  m <- read_fbm(path, game = "ghouls")
  expect_equal(dim(m$inputs), c(192L, 2L, 7L))
  keys <- button_layout(m)$key
  expect_true(all(m$inputs[17:80, 1, match("dpad_right", keys)]))
  expect_equal(which(m$inputs[, 1, match("b", keys)]), c(43:56, 121:134))
  expect_equal(which(m$inputs[, 2, match("start", keys)]), 165:166)
  expect_equal(which(system_channels(m)$coin_1), 1:2)
  expect_equal(system_channels(m)$dip_a, rep(255L, 192))
  expect_equal(system_channels(m)$raw_p1_dpad_right, as.integer(m$inputs[, 1, match("dpad_right", keys)]))
  expect_equal(read_movie(path, game = "ghouls")$inputs, m$inputs)
})
test_that("FBM analog values, nonbinary source bytes, and DIP values remain exact", {
  schema <- jsonlite::fromJSON(fbm_example("synthetic-arcade-analog-schema.json"), simplifyVector = FALSE)
  m <- read_fbm(fbm_example("synthetic-arcade-analog.fbm"), input_schema = schema)
  expect_equal(analog_channels(m, 1L)[, "stick_x"], c(0, 1000, 2000, 0, -2000, -32768, 0, 0))
  expect_equal(analog_channels(m, 1L)[, "stick_y"], c(0, 0, 1000, 2000, 1000, 32767, 0, 0))
  expect_equal(analog_channels(m, 2L)[, "dial"], c(0, 64, 128, 192, -64, -32768, 32767, 0))
  expect_equal(system_channels(m)$dip_a, c(255, 255, 255, 254, 254, 128, 0, 255))
  expect_equal(system_channels(m)$raw_p1_dpad_right, c(0, 1, 1, 0, 128, 129, 0, 0))
  expect_equal(as.logical(m$inputs[, 1, 1]), c(FALSE, TRUE, TRUE, FALSE, FALSE, TRUE, FALSE, FALSE))
  expect_equal(as.logical(m$inputs[, 2, 1]), rep(FALSE, 8))
})
test_that("independent FGK decoder handles the full alphabet and repeated blocks", {
  path <- fbm_example("synthetic-fgk-alphabet.bin")
  bytes <- readBin(path, "raw", file.info(path)$size)
  expected <- c(as.raw(0:255), as.raw(255:0), rep(charToRaw("abracadabra"), 31), rep(as.raw(0:255), 2))
  expect_identical(replayr:::.fbm_fgk_decode(bytes[-(1:16)], length(expected)), expected)
  expect_error(replayr:::.fbm_fgk_decode(bytes[17:20], length(expected)), "Truncated")
  expect_error(replayr:::.fbm_fgk_decode(as.raw(0), 1), "Invalid")
  expect_identical(replayr:::.fbm_fgk_decode(raw(), 0), raw())
})
test_that("FBM requires explicit valid source schemas and validates frame boundaries", {
  path <- fbm_example("synthetic-arcade.fbm")
  expect_error(read_fbm(path), "supply a verified game")
  expect_error(read_fbm(path, game = "unknown"), "source-verified input_schema")
  expect_error(read_fbm(path, game = "ghouls", input_schema = list()), "either game or input_schema")
  expect_error(read_fbm(path, input_schema = list(fields = list())), "ordered fields list")
  field <- list(key = "a", player = 1L, type = "button")
  expect_error(replayr:::.fbm_frame_values(as.raw(c(0, 0, 1)), 1, list(field)), "Truncated FBM frame")
  expect_error(replayr:::.fbm_frame_values(as.raw(c(0, 1, 1, 255)), 1, list(field)), "index exceeds")
  expect_error(replayr:::.fbm_frame_values(as.raw(c(0, 255, 255)), 1, list(field)), "remains after")
  expect_error(replayr:::.fbm_frame_values(as.raw(c(2, 255)), 1, list(field)), "button value")
  broken <- readBin(path, "raw", file.info(path)$size)
  broken[38L] <- as.raw(1L)
  tmp <- tempfile(fileext = ".fbm")
  on.exit(unlink(tmp))
  writeBin(broken, tmp)
  expect_error(read_fbm(tmp, game = "ghouls"), "frequency-counter resets")
})
